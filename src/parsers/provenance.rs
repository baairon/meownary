//! AI provenance rules, ported from the open-source cleaner
//! guillaumemeyer/watermarks-remover (MIT licensed,
//! <https://github.com/guillaumemeyer/watermarks-remover>). meownary reads the
//! same marks that project removes and drops them with its own structural
//! removers: no external tools, no network.
//!
//! What lives here is the vocabulary the format parsers share:
//!
//! * C2PA content credentials: the JUMBF chunk and box names, and the
//!   ContentProvenanceBox user type that MP4, HEIC and AVIF files carry.
//! * The tool-name rule that makes a comment count as provenance
//!   ([`comment_is_provenance`]).
//! * [`unicode`]: the invisible-character, exotic-space and bidi rules for text.
//! * [`markup`]: finding the provenance comments of Markdown and HTML.
//!
//! The matchers are small hand-written scanners over lowercased text because
//! the crate carries no regex engine.

pub(crate) mod markup;
pub(crate) mod unicode;

/// The ContentProvenanceBox user type of a C2PA manifest in an ISO base media
/// file: `d8fec3d6-1b0e-483c-9297-5828877ec481`.
pub(crate) const C2PA_BMFF_UUID: [u8; 16] = [
    0xd8, 0xfe, 0xc3, 0xd6, 0x1b, 0x0e, 0x48, 0x3c, 0x92, 0x97, 0x58, 0x28, 0x87, 0x7e, 0xc4, 0x81,
];

/// The XMP box user type, `be7acfcb-97a9-42e8-9c71-999491e3afac`.
pub(crate) const XMP_BMFF_UUID: [u8; 16] = [
    0xbe, 0x7a, 0xcf, 0xcb, 0x97, 0xa9, 0x42, 0xe8, 0x9c, 0x71, 0x99, 0x94, 0x91, 0xe3, 0xaf, 0xac,
];

/// Whether the bytes right after a `uuid` fourcc start with the C2PA user
/// type, directly or after a 4-byte version and flags prefix.
pub(crate) fn is_c2pa_uuid_payload(after_fourcc: &[u8]) -> bool {
    after_fourcc.get(..16) == Some(&C2PA_BMFF_UUID[..])
        || after_fourcc.get(4..20) == Some(&C2PA_BMFF_UUID[..])
}

/// PNG chunk types that hold a C2PA manifest: `caBX` and the JUMBF types.
/// (Upstream also drops a `c2` family, but PNG chunk types are letters only,
/// so no valid chunk is named that way.)
pub(crate) fn is_c2pa_png_chunk(ty: &[u8; 4]) -> bool {
    matches!(ty, b"caBX" | b"juMB" | b"jumb")
}

/// A RIFF chunk id for a C2PA manifest (WebP), in either case.
pub(crate) fn is_c2pa_riff_chunk(fourcc: &[u8; 4]) -> bool {
    fourcc.eq_ignore_ascii_case(b"C2PA")
}

/// An ISO base media box type that is a JUMBF or C2PA container by name.
pub(crate) fn is_c2pa_box_name(kind: &[u8; 4]) -> bool {
    matches!(kind, b"jumb" | b"c2pa") || kind.starts_with(b"c2")
}

/// One token of a [`find_ci`] pattern.
#[derive(Clone, Copy)]
enum Tok {
    /// A literal, already lowercase.
    Lit(&'static str),
    /// Any one character but a newline, or nothing.
    AnyOpt,
    /// One character from the set, or nothing.
    SetOpt(&'static str),
    /// One whitespace character, or nothing.
    SpaceOpt,
    /// A word boundary before a word character.
    WordStart,
    /// One decimal digit.
    Digit,
}

use Tok::{AnyOpt, Digit, Lit, SetOpt, SpaceOpt, WordStart};

fn is_word(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

fn match_at(toks: &[Tok], text: &[char], i: usize) -> bool {
    let Some((tok, rest)) = toks.split_first() else {
        return true;
    };
    match *tok {
        Lit(s) => {
            let mut j = i;
            for c in s.chars() {
                if text.get(j) != Some(&c) {
                    return false;
                }
                j += 1;
            }
            match_at(rest, text, j)
        }
        AnyOpt => {
            text.get(i).is_some_and(|&c| c != '\n') && match_at(rest, text, i + 1)
                || match_at(rest, text, i)
        }
        SetOpt(set) => {
            text.get(i).is_some_and(|&c| set.contains(c)) && match_at(rest, text, i + 1)
                || match_at(rest, text, i)
        }
        SpaceOpt => {
            text.get(i).is_some_and(|c| c.is_whitespace()) && match_at(rest, text, i + 1)
                || match_at(rest, text, i)
        }
        WordStart => {
            let before = i.checked_sub(1).and_then(|p| text.get(p)).copied();
            let after = text.get(i).copied();
            before.is_none_or(|c| !is_word(c))
                && after.is_some_and(is_word)
                && match_at(rest, text, i)
        }
        Digit => text.get(i).is_some_and(char::is_ascii_digit) && match_at(rest, text, i + 1),
    }
}

/// Whether any of `patterns` matches anywhere in `text`, ignoring case.
fn find_ci(patterns: &[&[Tok]], text: &str) -> bool {
    let chars: Vec<char> = text.chars().flat_map(char::to_lowercase).collect();
    (0..=chars.len()).any(|i| patterns.iter().any(|p| match_at(p, &chars, i)))
}

/// A Markdown or HTML comment counts as provenance only when it names an AI
/// tool or says the content is AI-generated. A bare "generated by" is not
/// enough, so build-tool comments are kept.
pub(crate) fn comment_is_provenance(block: &str) -> bool {
    const P: &[&[Tok]] = &[
        &[Lit("claude")],
        &[Lit("anthropic")],
        &[Lit("openai")],
        &[Lit("chat"), SpaceOpt, Lit("gpt")],
        &[WordStart, Lit("gpt"), SetOpt("-"), Digit],
        &[Lit("gemini")],
        &[Lit("synthid")],
        &[Lit("copilot")],
        &[Lit("midjourney")],
        &[Lit("dall"), AnyOpt, Lit("e")],
        &[Lit("stable"), AnyOpt, Lit("diffusion")],
        &[WordStart, Lit("ai"), SetOpt("-_ "), Lit("generated")],
        &[Lit("c2pa")],
        &[Lit("content"), AnyOpt, Lit("credential")],
    ];
    find_ci(P, block)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn comments_of_ai_tools() {
        for yes in [
            "<!-- written with Claude -->",
            "<!-- ChatGPT -->",
            "<!-- chat gpt -->",
            "<!-- gpt-4 output -->",
            "<!-- GPT5 -->",
            "<!-- DALL-E image -->",
            "<!-- dalle -->",
            "<!-- Stable Diffusion -->",
            "<!-- AI-generated -->",
            "<!-- c2pa -->",
            "<!-- Copilot suggestion -->",
        ] {
            assert!(comment_is_provenance(yes), "{yes}");
        }
        for no in [
            "<!-- generated by hugo -->",
            "<!-- TOC -->",
            "<!-- mygpt-4 -->",
            "<!-- said generated -->",
            "<!-- gpt-x -->",
        ] {
            assert!(!comment_is_provenance(no), "{no}");
        }
    }

    #[test]
    fn c2pa_names() {
        assert!(is_c2pa_png_chunk(b"caBX"));
        assert!(is_c2pa_png_chunk(b"juMB"));
        assert!(!is_c2pa_png_chunk(b"tEXt"));
        assert!(is_c2pa_riff_chunk(b"c2pa"));
        assert!(is_c2pa_riff_chunk(b"C2PA"));
        assert!(!is_c2pa_riff_chunk(b"XMP "));
        assert!(is_c2pa_box_name(b"jumb"));
        assert!(!is_c2pa_box_name(b"moov"));
        let mut payload = C2PA_BMFF_UUID.to_vec();
        assert!(is_c2pa_uuid_payload(&payload));
        payload.splice(0..0, [0, 0, 0, 0]);
        assert!(is_c2pa_uuid_payload(&payload));
        assert!(!is_c2pa_uuid_payload(&XMP_BMFF_UUID));
    }
}
